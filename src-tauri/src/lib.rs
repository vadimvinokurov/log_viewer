mod driver;
mod ipc;

/// Smoke command used by the scaffold; real commands live in ipc.rs.
#[tauri::command]
#[specta::specta]
fn ping_core() -> String {
  logviewer_core::version()
}

fn dirs_home() -> std::path::PathBuf {
  std::env::temp_dir()
}

/// The shared specta builder: commands of the IPC contract (docs/STACK.md
/// "IPC layer"; dsq.3 visibility bridge commands live in ipc.rs).
fn build_bindings() -> tauri_specta::Builder<tauri::Wry> {
  tauri_specta::Builder::<tauri::Wry>::new().commands(tauri_specta::collect_commands![
    ping_core,
    ipc::load_file,
    ipc::get_rows,
    ipc::add_filter,
    ipc::add_pin,
    ipc::set_filter_enabled,
    ipc::set_pin_enabled,
    ipc::remove_filter,
    ipc::remove_pin,
    ipc::clear_pins,
    ipc::clear_filters,
    ipc::set_level_enabled,
    ipc::set_category_enabled,
    ipc::visibility_snapshot,
    ipc::search_visible,
    ipc::add_highlight,
    ipc::remove_highlight,
    ipc::set_highlight_enabled,
    ipc::set_highlight_color,
    ipc::clear_highlights,
    driver::driver_report
  ])
}

/// TypeScript bindings are regenerated by cargo test (see the test below) so
/// `ui/src/bindings.ts` always matches the shipped command set.
#[cfg(test)]
mod tests {
  #[test]
  fn export_typescript_bindings() {
    super::build_bindings()
      .export(
        specta_typescript::Typescript::default(),
        "../ui/src/bindings.ts",
      )
      .expect("failed to export typescript bindings");
  }
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
  let bindings = build_bindings();
  #[cfg(debug_assertions)]
  bindings
    .export(specta_typescript::Typescript::default(), "../ui/src/bindings.ts")
    .expect("failed to export typescript bindings");

  tauri::Builder::default()
    .plugin(tauri_plugin_dialog::init())
    .plugin(tauri_plugin_clipboard_manager::init())
    .manage(ipc::new_file_state())
    .manage(ipc::new_visibility_state())
    .manage(ipc::new_highlight_state())
    .invoke_handler(bindings.invoke_handler())
    .setup(|app| {
      if cfg!(debug_assertions) {
        app.handle().plugin(
          tauri_plugin_log::Builder::default()
            .level(log::LevelFilter::Info)
            .build(),
        )?;
        // Live-verification driver (n4y.3): localhost HTTP -> headless console
        // in the real webview. Debug builds only.
        let port_file = dirs_home().join("logviewer.driver.port");
        driver::start(app.handle().clone(), port_file).ok();
      }
      Ok(())
    })
    .run(tauri::generate_context!())
    .expect("error while building tauri application");
}
